/**
 * The change-ticket runner — ticket 026's pass as a CLI.
 *
 *   npx tsx src/lib/change/run.ts <command> --slug <slug> [options]
 *
 * One command per stage, and each refuses to run out of order:
 *
 *   open      pull the live spec + the paid pass → changes/<ISO>/        → REVIEW
 *   review    write delta.md; `--approve` is the owner's gate            → BUILD
 *   build     assemble spec.json, `next build`                            → QA
 *   qa        fast gate always, full suite on major (009 §8)              → STAGING
 *   stage     deploy.ts STAGING on the built out/, overwrite the manifest → APPROVE
 *   approve   `--evidence` of the client's sign-off — the client's gate   → DEPLOY
 *   deploy    deploy.ts DEPLOY (no rebuild), then seed spec.json as live
 *
 * Ticket 031 adds a second carrier: when the live document is a hand-built site, BUILD, QA,
 * STAGING and DEPLOY run that site's own scripts instead (`annotated.ts`), and DEPLOY
 * rehearses unless `--live` — its target is a repo the client's DNS serves.
 *   close     close the pass in D1; the editor unlocks                   → CLOSED
 *
 * Plus `status`, `inbox` (every pass, unbound first), `bind` and `record`.
 *
 * What this deliberately does not do:
 *
 * - **Call `analysis/run.ts`.** 026 §0: it regenerates from intake and would wipe every
 *   post-launch self-edit. The live spec is the input. If a major ticket needs new copy,
 *   that is written into `spec.json` during REVIEW, not generated by a fresh ANALYSIS run.
 * - **Write `state.md`.** Propose-class. Every transition prints the diff and the Stage
 *   Log row; the owner pastes them.
 * - **Skip the seed.** DEPLOY puts the pass's bytes live, but post-launch the spec is
 *   cloud-owned (012 §6). Without the seed the client's next self-edit publish would
 *   rebuild from the pre-pass spec and silently revert the work they paid for — so
 *   `deploy` does not return success until the spec is seeded, and `close` refuses
 *   without a seeded version.
 *
 * `--dry-run` is a rehearsal: no wrangler, no portal, but the pass folder IS written so
 * the whole sequence can be walked. It therefore refuses the real Vault — rehearse with
 * `--vault-root <scratch dir>`.
 */

interface Flags {
  command: string;
  values: Record<string, string>;
  switches: Set<string>;
}

function parseArgs(argv: string[]): Flags {
  const [command = "", ...rest] = argv;
  const values: Record<string, string> = {};
  const switches = new Set<string>();
  for (let i = 0; i < rest.length; i++) {
    if (!rest[i].startsWith("--")) continue;
    const key = rest[i].slice(2);
    const next = rest[i + 1];
    if (next !== undefined && !next.startsWith("--")) {
      values[key] = next;
      i++;
    } else switches.add(key);
  }
  return { command, values, switches };
}

interface Context {
  flags: Flags;
  vaultRoot: string;
  dryRun: boolean;
  portal: PortalOptions;
}

function need(ctx: Context, name: string): string {
  const value = ctx.flags.values[name];
  if (!value) throw new Error(`--${name} is required for \`${ctx.flags.command}\``);
  return value;
}

function loadSpec(file: string): SiteSpec {
  const result = z.safeParse(siteSpecSchema, JSON.parse(fs.readFileSync(file, "utf-8")));
  if (!result.success) throw new Error(`${file} does not validate:\n${z.prettifyError(result.error)}`);
  return result.data;
}

function readJson<T>(file: string): T {
  return JSON.parse(fs.readFileSync(file, "utf-8")) as T;
}

function writeJson(file: string, value: unknown): void {
  fs.writeFileSync(file, JSON.stringify(value, null, 2) + "\n", "utf-8");
}

const TEMPLATE_BEFORE = "template.before.html";

/** The client site behind an annotated pass, as `open` pinned it. */
function siteOf(state: PassState): AnnotatedSite {
  if (!state.siteDir) throw new Error(`${state.slug} is an annotated pass with no site directory recorded.`);
  return resolveSite(state.siteDir);
}

function frontmatterOf(ctx: Context, slug: string): Record<string, string> {
  const file = path.join(clientDir(slug, ctx.vaultRoot), "state.md");
  if (!fs.existsSync(file)) throw new Error(`No client record at ${file}`);
  return readFrontmatter(fs.readFileSync(file, "utf-8"));
}

function requireOpenPass(ctx: Context, slug: string): { dir: string; state: PassState } {
  const dir = openPassDir(slug, ctx.vaultRoot);
  if (!dir) throw new Error(`${slug} has no open change pass. Start one with \`open\`.`);
  return { dir, state: readPass(dir) };
}

/** Writes the transition, then prints what `state.md` should say about it. */
function transition(
  ctx: Context,
  dir: string,
  state: PassState,
  to: PassStage,
  event: string,
  proposal?: { stage?: string; relationship?: string; substatus?: string },
): PassState {
  const next = advance(state, to, event);
  writePass(dir, next);
  console.log(`\n  pass → ${to}. Next: \`${nextCommand(to)}\``);
  if (proposal) {
    console.log(`\n${stateProposal(frontmatterOf(ctx, state.slug), proposal, event)}`);
  }
  return next;
}

function substatus(state: PassState, words: string): string {
  return `Change ticket (${state.klass} × ${state.quantity}) — ${words}`;
}

/** BUILD's tree, still there. A second session building into the same `out/` is real (SESSION-BRIEF §7). */
/**
 * The built tree, re-hashed and compared to what BUILD pinned — SESSION-BRIEF §7: one
 * Worker, one working tree. On the annotated carrier the tree is the surface materialised
 * into the pass folder, so the check takes the manifest rather than re-deriving `out/`.
 */
function assertPinnedTree(state: PassState, manifest: ArtifactManifest): ArtifactManifest {
  if (manifest.treeHash !== state.builtTreeHash) {
    throw new Error(
      `The built page is ${manifest.treeHash.slice(0, 12)}, not what BUILD left ` +
        `(${state.builtTreeHash?.slice(0, 12)}). Something rebuilt it since — run \`build\` again.`,
    );
  }
  return manifest;
}

function assertBuiltTree(state: PassState): ArtifactManifest {
  const current = computeManifest(path.join(PROJECT_ROOT, "out"), state.slug);
  if (current.treeHash !== state.builtTreeHash) {
    throw new Error(
      `out/ is not the tree BUILD produced (${state.builtTreeHash?.slice(0, 12) ?? "none"} → ` +
        `${current.treeHash.slice(0, 12)}). Something else built into this checkout. Run \`build\` again.`,
    );
  }
  return current;
}

